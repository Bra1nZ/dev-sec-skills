#!/usr/bin/env python3
"""Step 4: generate the model from approved primitives only.

Two artifacts come out of here:

* ``generated/model.json`` — the machine-readable model, one entry per approved
  primitive, every entry still carrying its anchor;
* ``generated/model.sys`` — a B skeleton. It is a skeleton on purpose: Rust
  expressions are not translated, and a translated-looking expression that was
  guessed would be worse than a comment. Anything not translated is written as
  a comment next to the operation.

``proposed``, ``rejected``, ``deferred`` and ``unmapped`` never enter the model;
their ids are listed under ``excluded`` so the omission is counted, not hidden.
Test code is excluded by default (``--include-tests`` puts it back), and an
``assert!`` invariant follows its operation: approving the operation approves
the assert, recorded in ``decided_by``. A private, read-only operation without
a decision lands in the ``not_required`` bucket; approving it explicitly by
adding a decision entry still works.

Exit codes: 0 ok, 1 nothing was approved (the model would be empty), 2 usage.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import time

from model_primitives import (
    FORMAT_MODEL, ModelError, add_target_args, decision_map, journal_crash,
    load_decisions, load_primitives, now_iso, prepare, sha256_file,
    tool_block, write_json,
)

B_MACHINE = re.compile(r"[^A-Za-z0-9_]")


def machine_name(target_name: str) -> str:
    name = B_MACHINE.sub("_", target_name or "model")
    if not name or not name[0].isalpha():
        name = "m_" + name
    return name.lower()


def b_set_name(name: str) -> str:
    cleaned = B_MACHINE.sub("_", name).upper()
    return cleaned if cleaned[0].isalpha() else "S_" + cleaned


def b_type(rust_type: str, enum_names) -> str:
    """Translate the cheap cases; return ``""`` when the type is unknown."""
    text = (rust_type or "").strip()
    text = text.replace("&mut ", "").replace("&", "").strip()
    match = re.match(r"^(?:BTreeSet|HashSet|VecDeque|Vec|Option|Box)<(.+)>$", text)
    if match:
        inner = match.group(1).strip()
        if text.startswith(("BTreeSet", "HashSet")):
            return "POW(%s)" % (b_set_name(inner) if inner in enum_names
                                else b_type(inner, enum_names) or "NAT")
        if text.startswith("Vec"):
            return "seq(%s)" % (b_set_name(inner) if inner in enum_names
                                else b_type(inner, enum_names) or "NAT")
        if text.startswith("Option"):
            return b_type(inner, enum_names) or "NAT"
        return b_type(inner, enum_names) or ""
    simple = {
        "usize": "NAT", "u8": "NAT", "u16": "NAT", "u32": "NAT",
        "u64": "NAT", "u128": "NAT", "i8": "INT", "i16": "INT",
        "i32": "INT", "i64": "INT", "i128": "INT", "bool": "BOOL",
    }
    if text in simple:
        return simple[text]
    if text in enum_names:
        return b_set_name(text)
    return ""


def param_parts(signature: str):
    """Crude parameter split for the skeleton: enough for a B signature."""
    inside = signature.split("(", 1)
    if len(inside) != 2:
        return []
    body = inside[1].rsplit(")", 1)[0]
    parts = []
    depth = 0
    current = []
    for ch in body:
        if ch in "<([":
            depth += 1
        elif ch in ">)]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(current).strip())
            current = []
        else:
            current.append(ch)
    if "".join(current).strip():
        parts.append("".join(current).strip())
    out = []
    for part in parts:
        if "self" in part and "Self" not in part:
            continue
        if ":" not in part:
            continue
        name, type_text = part.split(":", 1)
        name = name.strip().replace("mut ", "")
        if name.startswith("&"):
            continue
        out.append((name, type_text.strip()))
    return out


def generate_sys(model: dict, primitives: dict) -> str:
    lines = []
    add = lines.append
    target = model.get("target") or {}
    add("/* Generated by tools/model_gen.py from approved primitives.")
    add(" * Target: %s @ %s" % (target.get("path"),
                                target.get("commit") or "no commit"))
    add(" * This is a SKELETON. Guards and effects whose Rust expression was")
    add(" * not translated appear as comments. Do not treat it as provable.")
    add(" */")
    add("MACHINE %s" % model["machine"])
    add("")
    if model["sets"]:
        add("SETS")
        for entry in model["sets"]:
            values = ", ".join(entry["values"]) if entry["values"] else "{}"
            add("  %s = {%s}" % (b_set_name(entry["name"]), values))
        add("")
    add("VARIABLES")
    for variable in model["variables"]:
        add("  %s" % variable["name"])
    for skipped in model["unknown_types"]:
        add("  /* skipped: %s : %s (type not translated) */"
            % (skipped["name"], skipped["type"]))
    add("")
    add("INVARIANT")
    for variable in model["variables"]:
        if variable["b_type"]:
            add("  %s : %s" % (variable["name"], variable["b_type"]))
    for invariant in model["invariants"]:
        add("  /* candidate invariant [%s]: %s */"
            % (invariant["id"], invariant["text"]))
    add("")
    add("INITIALISATION")
    for variable in model["variables"]:
        add("  %s := %s" % (variable["name"], variable["init"]))
    add("")
    add("OPERATIONS")
    for operation in model["operations"]:
        params = ", ".join(name for name, _ in operation["params"]) or ""
        add("  %s(%s) =" % (operation["name"], params))
        add("  BEGIN")
        if operation["guards"]:
            for guard in operation["guards"]:
                add("    /* guard: %s (reject when %s) */"
                    % (guard["condition"], guard["reject_when"]))
        for effect in operation["effects"]:
            if effect.get("b"):
                add("    %s" % effect["b"])
            else:
                add("    /* effect: %s */" % effect["rust"])
        if not operation["effects"] and not operation["guards"]:
            add("    skip")
        elif not any(effect.get("b") for effect in operation["effects"]):
            add("    skip /* TODO: no effect was translated */")
        add("  END")
        add("")
    add("END")
    return "\n".join(lines) + "\n"


def init_value(b_type: str) -> str:
    if b_type.startswith("POW("):
        return "{}"
    if b_type.startswith("seq("):
        return "[]"
    if b_type == "BOOL":
        return "FALSE"
    if b_type in ("NAT", "INT"):
        return "0"
    return "{}"


def main(argv) -> int:
    ap = argparse.ArgumentParser(
        description="Generate the model from approved primitives.")
    add_target_args(ap)
    ap.add_argument("--include-tests", action="store_true",
                    help="include test code (excluded by default)")
    args = ap.parse_args(argv)

    info, out, console, journal = prepare(args, "gen")
    started = time.time()
    try:
        primitives = load_primitives(out)
        decisions = load_decisions(out)
        chosen = decision_map(decisions)

        approved = {primitive_id for primitive_id, entry in chosen.items()
                    if entry.get("decision") == "approved"}

        def keep(primitive):
            """Approved, and not test code unless tests are included."""
            if primitive.get("test") and not args.include_tests:
                return False
            return primitive["id"] in approved

        entities = [e for e in primitives.get("entities") or [] if keep(e)]
        state = [s for s in primitives.get("state") or [] if keep(s)]
        operations = [o for o in primitives.get("operations") or [] if keep(o)]
        invariants = []
        decided_by = {}
        approved_ops = {operation["id"] for operation in operations}
        for invariant in primitives.get("invariants") or []:
            own = invariant["id"] in approved
            # An assert invariant follows its operation: approving the
            # operation approves the assert, recorded as a group decision.
            group = invariant.get("kind") == "assert" \
                and invariant.get("scope") in approved_ops
            if invariant.get("test") and not args.include_tests:
                continue
            if own or group:
                invariants.append(invariant)
                decided_by[invariant["id"]] = \
                    None if own else invariant.get("scope")

        if not entities and not operations:
            raise ModelError(
                "nothing is approved in decisions.yaml; the model would be "
                "empty. Run model-review, decide, then model-gen again.")

        enum_names = {e["name"] for e in entities if e["kind"] == "enum"}
        sets = [{"id": e["id"], "name": e["name"],
                 "values": [v["name"] for v in e.get("variants") or []],
                 "anchor": e.get("anchor")}
                for e in entities if e["kind"] == "enum"]

        variables, unknown_types = [], []
        for entry in state:
            b_type_text = b_type(entry.get("type"), enum_names)
            name = entry["field"]
            if b_type_text:
                variables.append({
                    "id": entry["id"], "name": name,
                    "entity": entry.get("entity"),
                    "rust_type": entry.get("type"),
                    "b_type": b_type_text,
                    "init": init_value(b_type_text),
                    "anchor": entry.get("anchor"),
                })
            else:
                unknown_types.append({"id": entry["id"], "name": name,
                                      "type": entry.get("type")})

        model_operations = []
        var_types = {v["name"]: v["b_type"] for v in variables}
        for op in operations:
            params = [(name, rust_type) for name, rust_type
                      in param_parts(op["signature"])]
            effects, effects_rust = [], []
            for effect in op.get("effects") or []:
                rust_text = "%s.%s(%s)" % (
                    effect["target"], effect.get("method", ""),
                    effect.get("value", "")) if effect["kind"] == "method" \
                    else "%s %s %s" % (effect["target"],
                                       effect.get("operator", ":="),
                                       effect.get("value", ""))
                translated = translate_effect(effect, var_types)
                effects.append({"b": translated, "rust": rust_text,
                                "kind": effect["kind"]})
                effects_rust.append(rust_text)
            model_operations.append({
                "id": op["id"],
                "name": op["name"],
                "owner": op.get("owner"),
                "params": params,
                "mut_self": op.get("mut_self"),
                "guards": op.get("guards") or [],
                "effects": effects,
                "anchor": op.get("anchor"),
            })

        payload = {
            "format": FORMAT_MODEL,
            "generated": now_iso(),
            "tool": tool_block("model_gen"),
            "target": primitives.get("target"),
            "machine": machine_name((primitives.get("target") or {}).get("name")),
            "source": {
                "primitives": os.path.join(out, "primitives.yaml"),
                "primitives_sha256": sha256_file(
                    os.path.join(out, "primitives.yaml")),
                "decisions_sha256": sha256_file(
                    os.path.join(out, "decisions.yaml"))
                if os.path.isfile(os.path.join(out, "decisions.yaml")) else None,
            },
            "status": "open",
            "sets": sets,
            "variables": variables,
            "unknown_types": unknown_types,
            "operations": model_operations,
            "invariants": [{"id": i["id"], "kind": i["kind"],
                            "text": i["text"], "scope": i.get("scope"),
                            "decided_by": decided_by.get(i["id"]),
                            "anchor": i.get("anchor")} for i in invariants],
            "excluded": excluded_ids(primitives, chosen, args.include_tests),
            "counts": {
                "entities": len(entities),
                "sets": len(sets),
                "variables": len(variables),
                "unknown_types": len(unknown_types),
                "operations": len(model_operations),
                "invariants": len(invariants),
                "approved": len(approved),
                "group_decided": sum(1 for value in decided_by.values()
                                     if value),
            },
        }

        gen_dir = os.path.join(out, "generated")
        os.makedirs(gen_dir, exist_ok=True)
        json_path = os.path.join(gen_dir, "model.json")
        sys_path = os.path.join(gen_dir, "model.sys")
        write_json(json_path, payload)
        with open(sys_path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(generate_sys(payload, primitives))

        console("gen: %s" % json_path)
        console("  machine    %s" % payload["machine"])
        console("  sets       %d   variables %d (unknown types %d)"
                % (len(sets), len(variables), len(unknown_types)))
        console("  operations %d   invariants %d"
                % (len(model_operations), len(invariants)))
        console("  excluded   %d ids (proposed/rejected/deferred/unmapped)"
                % sum(len(v) for v in payload["excluded"].values()))

        journal.write(
            argv=sys.argv[1:], target=info["path"],
            target_commit=info["commit"], dirty=info["dirty"],
            exit_code=0,
            duration_ms=int((time.time() - started) * 1000),
            inputs=[{"path": os.path.join(out, "primitives.yaml"),
                     "sha256": sha256_file(os.path.join(out, "primitives.yaml"))}],
            outputs=[{"path": json_path, "sha256": sha256_file(json_path)},
                     {"path": sys_path, "sha256": sha256_file(sys_path)}],
            counts=payload["counts"], status="ok",
        )
        print("gen: %d sets, %d variables, %d operations, %d invariants"
              % (len(sets), len(variables), len(model_operations),
                 len(invariants)))
        return 0
    except ModelError as exc:
        console("gen: %s" % exc)
        journal.write(argv=sys.argv[1:], target=info["path"],
                      target_commit=info["commit"], dirty=info["dirty"],
                      exit_code=1,
                      duration_ms=int((time.time() - started) * 1000),
                      status="error", error=str(exc))
        return 1
    except Exception as exc:  # noqa: BLE001 - a crash must still be journaled
        journal_crash(console, journal, exc, started, argv=sys.argv[1:],
                      target=info["path"], target_commit=info["commit"],
                      dirty=info["dirty"])
        return 2
    finally:
        console.close()


def translate_effect(effect, var_types) -> str:
    """Translate only the effects whose meaning is unambiguous.

    An effect whose value is a Rust expression (``"x".to_string()``,
    ``BTreeSet::new()``) is left as a comment: a guessed B expression would be
    indistinguishable from a checked one.
    """
    target = effect["target"].replace("self.", "")
    b_type_text = var_types.get(target, "")

    def simple(value):
        value = (value or "").strip()
        if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", value):
            return value
        if re.fullmatch(r"[0-9]+", value):
            return value
        return None

    if effect["kind"] == "method":
        method = effect.get("method")
        value = simple(effect.get("value"))
        if method == "insert" and value:
            return "%s := %s \\/ {%s}" % (target, target, value)
        if method == "remove" and value:
            return "%s := %s - {%s}" % (target, target, value)
        if method == "clear":
            if b_type_text.startswith("seq("):
                return "%s := []" % target
            return "%s := {}" % target
        if method == "push" and value:
            return "%s := %s ^ [%s]" % (target, target, value)
        return ""
    if effect["kind"] == "init":
        return ""
    value = simple(effect.get("value"))
    if effect.get("operator") == "=" and value:
        return "%s := %s" % (target, value)
    return ""


def excluded_ids(primitives, chosen, include_tests=False) -> dict:
    buckets = {"proposed": [], "rejected": [], "deferred": [], "unmapped": [],
               "test": [], "not_required": []}
    for section in ("entities", "state", "operations", "invariants"):
        for primitive in primitives.get(section) or []:
            decision = (chosen.get(primitive["id"]) or {}).get("decision")
            if decision == "approved":
                if primitive.get("test") and not include_tests:
                    buckets["test"].append(primitive["id"])
                continue
            if decision in ("rejected", "deferred"):
                buckets[decision].append(primitive["id"])
            elif primitive.get("test") and not include_tests:
                buckets["test"].append(primitive["id"])
            elif not primitive.get("required", True):
                buckets["not_required"].append(primitive["id"])
            else:
                buckets["proposed"].append(primitive["id"])
    for entry in primitives.get("unmapped") or []:
        buckets["unmapped"].append(entry["id"])
    return buckets


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
