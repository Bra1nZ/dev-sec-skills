#!/usr/bin/env python3
"""Structural items in a Rust file: structs, enums, impls, functions.

Built on :mod:`rust_lexer`. The parser understands the shapes the conveyor
needs and refuses to guess about anything else: an item it cannot delimit is
reported back as ``unsupported`` instead of producing a half-item.

What is recognised:

* ``struct`` with named fields, tuple fields or unit form;
* ``enum`` with unit, tuple and struct variants;
* ``impl`` blocks, including ``impl Trait for Type``;
* ``fn`` with generics, ``where`` clauses, receivers and bodies;
* ``trait`` blocks (their default bodies are parsed as operations);
* ``mod`` blocks (recursed into), ``use``/``const``/``static``/``type``
  (skipped).

What is not recognised, and is reported as ``unsupported``: items generated by
``macro_rules!`` and anything inside a ``macro_rules!`` body.
"""

from __future__ import annotations

from rust_lexer import DOC, IDENT, PUNCT, STR, lex

_ITEM_KEYWORDS = {"struct", "enum", "impl", "fn", "trait", "mod", "use",
                  "const", "static", "type", "macro_rules", "extern"}
_MODIFIERS = {"const", "async", "unsafe", "default", "extern"}
_TYPE_WORDS = {"dyn", "const", "unsafe", "mut", "impl", "for", "where",
               "Trait", "Self"}


class ParseError(Exception):
    def __init__(self, message: str, line: int = 0):
        self.message = message
        self.line = line
        super().__init__("%s at line %d" % (message, line) if line else message)


def _is_ident(token, text=None) -> bool:
    if token.kind != IDENT:
        return False
    return text is None or token.text == text


class Parser:
    def __init__(self, lexed):
        self.lx = lexed
        self.t = lexed.tokens
        self.pairs = lexed.pairs
        self.unsupported = []

    # -- helpers ----------------------------------------------------------

    def _skip_attrs(self, i: int, end: int) -> int:
        while i < end and self.t[i].kind == PUNCT and self.t[i].text == "#":
            j = i + 1
            if j < end and self.t[j].text == "!":
                j += 1
            if j < end and self.t[j].text == "[":
                close = self.pairs.get(j)
                if close is None:
                    raise ParseError("unclosed attribute", self.t[j].line)
                i = close + 1
                continue
            break
        return i

    def _visibility(self, i: int, end: int):
        if i < end and _is_ident(self.t[i], "pub"):
            j = i + 1
            if j < end and self.t[j].text == "(":
                j = self.pairs[j] + 1
            return "public", j
        return "private", i

    def _skip_modifiers(self, i: int, end: int) -> int:
        while i < end:
            tok = self.t[i]
            if tok.kind == IDENT and tok.text in _MODIFIERS:
                i += 1
                if tok.text == "extern" and i < end and self.t[i].kind == STR:
                    i += 1
                continue
            break
        return i

    def _skip_generics(self, i: int, end: int) -> int:
        if i < end and self.t[i].text == "<":
            depth = 0
            while i < end:
                text = self.t[i].text
                if text == "<":
                    depth += 1
                elif text == ">":
                    depth -= 1
                    if depth == 0:
                        return i + 1
                i += 1
        return i

    def _to_body(self, i: int, end: int, stops=("{", "(", ";")):
        """Index of the first ``stops`` token at bracket depth 0."""
        depth = 0
        while i < end:
            tok = self.t[i]
            if tok.kind == PUNCT:
                if tok.text in ("(", "["):
                    depth += 1
                elif tok.text in (")", "]"):
                    depth -= 1
                elif tok.text in stops and depth == 0:
                    return i
                elif tok.text == "{":
                    if depth == 0 and "{" in stops:
                        return i
                    depth += 1
                elif tok.text == "}":
                    depth -= 1
            i += 1
        return -1

    def _split_top(self, first: int, last: int, sep: str = ",") -> list:
        parts, current, depth = [], [], 0
        i = first
        while i <= last:
            tok = self.t[i]
            if tok.kind == PUNCT:
                if tok.text in ("(", "[", "{", "<"):
                    depth += 1
                elif tok.text in (")", "]", "}", ">"):
                    depth -= 1
                elif tok.text == sep and depth == 0:
                    parts.append(current)
                    current = []
                    i += 1
                    continue
            current.append(i)
            i += 1
        if current:
            parts.append(current)
        return [part for part in parts if part]

    def _text(self, first: int, last: int) -> str:
        if first > last:
            return ""
        return self.lx.text_between(first, last)

    def _doc_text(self, docs) -> str:
        out = []
        for token in docs:
            text = token.text
            if text.startswith("///"):
                body = text[3:]
            elif text.startswith("//!"):
                body = text[3:]
            elif text.startswith("//"):
                body = text[2:]
            else:
                body = text[2:-2]
                body = body.lstrip("*")
            body = body.strip()
            if body:
                out.append(body)
        return "\n".join(out)

    def _decl_start(self, start_idx: int) -> int:
        """First token of the declaration itself, after docs and attributes."""
        i = start_idx
        while i < len(self.t):
            tok = self.t[i]
            if tok.kind == DOC:
                i += 1
                continue
            if tok.kind == PUNCT and tok.text == "#":
                try:
                    i = self._skip_attrs(i, len(self.t))
                except ParseError:
                    return i
                continue
            break
        return i

    def _item(self, kind, name, owner, visibility, docs, start_idx, end_line):        return {
            "kind": kind,
            "name": name,
            "owner": owner,
            "visibility": visibility,
            "docs": self._doc_text(docs),
            "start_line": self.t[start_idx].line,
            "end_line": end_line,
        }

    # -- items ------------------------------------------------------------

    def parse_items(self, start: int, end: int, owner=None, in_trait=False):
        items = []
        i = start
        pending_docs = []
        decl_start = None
        while i < end:
            tok = self.t[i]
            if tok.kind == DOC:
                pending_docs.append(tok)
                if decl_start is None:
                    decl_start = i
                i += 1
                continue
            if tok.kind == PUNCT and tok.text == "#":
                if decl_start is None:
                    decl_start = i
                try:
                    i = self._skip_attrs(i, end)
                except ParseError as exc:
                    self.unsupported.append({
                        "line": exc.line, "reason": "parse-error",
                        "detail": exc.message,
                    })
                    i += 1
                continue
            if tok.kind == PUNCT and tok.text in (";", "}"):
                pending_docs = []
                decl_start = None
                i += 1
                continue
            if tok.kind != IDENT:
                i += 1
                continue

            word = tok.text
            if word == "macro_rules":
                self.unsupported.append({
                    "line": tok.line, "reason": "macro_rules",
                    "detail": "items generated by macro_rules are not parsed",
                })
                i = self._skip_to_semicolon_or_block(i, end)
                pending_docs = []
                decl_start = None
                continue
            if word not in _ITEM_KEYWORDS and word != "pub" \
                    and word not in _MODIFIERS:
                if decl_start is None:
                    decl_start = i
                i += 1
                continue

            start_idx = decl_start if decl_start is not None else i
            j = self._skip_attrs(i, end)
            visibility, j = self._visibility(j, end)
            if j >= end:
                break
            if self.t[j].kind == IDENT and self.t[j].text in _MODIFIERS:
                after = self._skip_modifiers(j, end)
                if after < end and self.t[after].kind == IDENT \
                        and self.t[after].text in _ITEM_KEYWORDS:
                    j = after
            word = self.t[j].text

            if word not in _ITEM_KEYWORDS and word != "macro_rules":
                i += 1
                continue

            try:
                if word == "mod":
                    nested, nxt = self._mod(j, end, owner, in_trait)
                    items.extend(nested)
                elif word == "struct":
                    item, nxt = self._struct(j, end, visibility, pending_docs,
                                             start_idx)
                    items.append(item)
                elif word == "enum":
                    item, nxt = self._enum(j, end, visibility, pending_docs,
                                           start_idx)
                    items.append(item)
                elif word == "impl":
                    nested, nxt = self._impl(j, end, pending_docs)
                    items.extend(nested)
                elif word == "trait":
                    nested, nxt = self._trait(j, end, visibility, pending_docs)
                    items.extend(nested)
                elif word == "fn":
                    item, nxt = self._fn(j, end, owner, visibility,
                                         pending_docs, in_trait, start_idx)
                    items.append(item)
                else:
                    nxt = self._skip_to_semicolon_or_block(j, end)
            except ParseError as exc:
                self.unsupported.append({
                    "line": exc.line or self.t[start_idx].line,
                    "reason": "parse-error",
                    "detail": exc.message,
                })
                nxt = self._skip_to_semicolon_or_block(j, end)
            pending_docs = []
            decl_start = None
            i = max(nxt, i + 1)
        return items

    def _skip_to_semicolon_or_block(self, i: int, end: int) -> int:
        while i < end:
            tok = self.t[i]
            if tok.kind == PUNCT:
                if tok.text == ";":
                    return i + 1
                if tok.text == "{":
                    close = self.pairs.get(i)
                    return (close + 1) if close is not None else end
            i += 1
        return end

    def _mod(self, i, end, owner, in_trait):
        if i + 1 >= end or not _is_ident(self.t[i + 1]):
            return [], i + 1
        j = i + 2
        if j < end and self.t[j].text == "{":
            close = self.pairs[j]
            return self.parse_items(j + 1, close, owner, in_trait), close + 1
        return [], self._skip_to_semicolon_or_block(j, end)

    def _struct(self, i, end, visibility, docs, start_idx):
        line = self.t[i].line
        if i + 1 >= end or not _is_ident(self.t[i + 1]):
            raise ParseError("struct without a name", line)
        name = self.t[i + 1].text
        j = self._skip_generics(i + 2, end)
        body = self._to_body(j, end, stops=("{", "(", ";"))
        if body < 0:
            raise ParseError("struct without a body", line)
        item = self._item("struct", name, None, visibility, docs, start_idx,
                          self.t[body].line)
        if self.t[body].text == "(":
            close = self.pairs[body]
            item["form"] = "tuple"
            item["fields"] = []
            item["end_line"] = self.t[close].line
            return item, close + 1
        if self.t[body].text == ";":
            item["form"] = "unit"
            item["fields"] = []
            return item, body + 1
        close = self.pairs[body]
        item["form"] = "named"
        item["fields"] = self._fields(body + 1, close)
        item["end_line"] = self.t[close].line
        return item, close + 1

    def _fields(self, first, last):
        fields = []
        for part in self._split_top(first, last - 1):
            k = 0
            while k < len(part) and self.t[part[k]].text == "#":
                j = part[k] + 1
                if j < len(self.t) and self.t[j].text == "!":
                    j += 1
                if j < len(self.t) and self.t[j].text == "[":
                    stop = self.pairs[j]
                    while k < len(part) and part[k] <= stop:
                        k += 1
                else:
                    break
            part = part[k:]
            if not part or not _is_ident(self.t[part[0]]):
                continue
            vis = "private"
            if self.t[part[0]].text == "pub":
                vis = "public"
                part = part[1:]
                if part and self.t[part[0]].text == "(":
                    close = self.pairs[part[0]]
                    part = [x for x in part if x > close]
            if not part or not _is_ident(self.t[part[0]]):
                continue
            colon = next((idx for idx in part
                          if self.t[idx].text == ":"), None)
            if colon is None:
                continue
            type_text = self._text(colon + 1, part[-1]).strip()
            fields.append({
                "name": self.t[part[0]].text,
                "type": type_text,
                "visibility": vis,
                "line": self.t[part[0]].line,
                "end_line": self.t[part[-1]].line,
            })
        return fields

    def _enum(self, i, end, visibility, docs, start_idx):
        line = self.t[i].line
        if i + 1 >= end or not _is_ident(self.t[i + 1]):
            raise ParseError("enum without a name", line)
        name = self.t[i + 1].text
        j = self._skip_generics(i + 2, end)
        body = self._to_body(j, end, stops=("{", ";"))
        if body < 0 or self.t[body].text != "{":
            raise ParseError("enum without a body", line)
        close = self.pairs[body]
        variants = []
        for part in self._split_top(body + 1, close - 1):
            k = 0
            while k < len(part) and self.t[part[k]].text == "#":
                jj = part[k] + 1
                if jj < len(self.t) and self.t[jj].text == "!":
                    jj += 1
                if jj < len(self.t) and self.t[jj].text == "[":
                    stop = self.pairs[jj]
                    while k < len(part) and part[k] <= stop:
                        k += 1
                else:
                    break
            part = part[k:]
            if not part or not _is_ident(self.t[part[0]]):
                continue
            variants.append({
                "name": self.t[part[0]].text,
                "line": self.t[part[0]].line,
                "end_line": self.t[part[-1]].line,
            })
        item = self._item("enum", name, None, visibility, docs, start_idx,
                          self.t[close].line)
        item["variants"] = variants
        item["fields"] = []
        item["form"] = "enum"
        return item, close + 1

    def _impl(self, i, end, docs):
        j = self._skip_generics(i + 1, end)
        owner_tokens = []
        k = j
        while k < end:
            tok = self.t[k]
            if tok.kind == PUNCT and tok.text == ";":
                return [], k + 1
            if tok.kind == PUNCT and tok.text == "{":
                break
            owner_tokens.append(k)
            k += 1
        if k >= end:
            return [], end
        idents = [idx for idx in owner_tokens if self.t[idx].kind == IDENT]
        owner = None
        for_marker = next((pos for pos, idx in enumerate(idents)
                           if self.t[idx].text == "for"), None)
        candidates = idents[for_marker + 1:] if for_marker is not None else idents
        for idx in candidates:
            text = self.t[idx].text
            if text in _TYPE_WORDS:
                continue
            owner = text
            break
        close = self.pairs[k]
        items = self.parse_items(k + 1, close, owner, in_trait=False)
        return items, close + 1

    def _trait(self, i, end, visibility, docs):
        j = i + 1
        if j >= end or not _is_ident(self.t[j]):
            raise ParseError("trait without a name", self.t[i].line)
        j = self._skip_generics(j + 1, end)
        body = self._to_body(j, end, stops=("{", ";"))
        if body < 0 or self.t[body].text != "{":
            return [], self._skip_to_semicolon_or_block(j, end)
        close = self.pairs[body]
        items = self.parse_items(body + 1, close, None, in_trait=True)
        return items, close + 1

    def _fn(self, i, end, owner, visibility, docs, in_trait, start_idx):
        line = self.t[i].line
        j = i + 1
        if j >= end or not _is_ident(self.t[j]):
            raise ParseError("fn without a name", line)
        name = self.t[j].text
        j += 1
        j = self._skip_generics(j, end)
        if j >= end or self.t[j].text != "(":
            raise ParseError("fn without a parameter list", line)
        params_close = self.pairs[j]
        params = self._split_top(j + 1, params_close - 1)
        receiver = None
        param_texts = []
        for part in params:
            text = self._text(part[0], part[-1]).strip()
            if text:
                param_texts.append(text)
            words = [self.t[idx].text for idx in part]
            if "self" in words and "Self" not in words:
                if "&" in words and "mut" in words:
                    receiver = "mut_ref"
                elif "&" in words:
                    receiver = "ref"
                else:
                    receiver = "value"
        k = params_close + 1
        while k < end:
            tok = self.t[k]
            if tok.kind == PUNCT and tok.text in ("{", ";"):
                break
            k += 1
        if k >= end:
            raise ParseError("fn without a body or terminator", line)
        if self.t[k].text == ";":
            body = None
            end_line = self.t[k].line
            nxt = k + 1
        else:
            close = self.pairs[k]
            body = (k + 1, close - 1)
            end_line = self.t[close].line
            nxt = close + 1
        signature = self._text(self._decl_start(start_idx), k - 1).strip()
        item = self._item("fn", name, owner, visibility, docs, start_idx,
                          end_line)
        item["signature"] = signature
        item["params"] = param_texts
        item["receiver"] = receiver
        item["mut_self"] = receiver in ("mut_ref", "value")
        item["in_trait"] = in_trait
        item["body"] = body
        item["declaration_only"] = body is None
        return item, nxt


def parse_source(source: str):
    lexed = lex(source)
    parser = Parser(lexed)
    items = parser.parse_items(0, len(lexed.tokens) - 1)
    return lexed, items, parser.unsupported


def parse_file(path: str):
    with open(path, "r", encoding="utf-8", newline="") as fh:
        source = fh.read()
    return parse_source(source)
