def repo_lines(repo, commit, path, cache):
    key = (commit, path)
    if key not in cache:
        proc = subprocess.run(["git", "show", "%s:%s" % (commit, path)],
                              cwd=repo, capture_output=True, text=True)
        if proc.returncode != 0:
            raise SystemExit("cannot read %s at %s: %s"
                             % (path, commit, proc.stderr.strip()))
        cache[key] = proc.stdout.splitlines()
    return cache[key]


def statement(lines, lineno):
    text = lines[lineno - 1]
    out = [text]
    depth = text.count("(") - text.count(")")
    i = lineno
    while depth > 0 and i < len(lines) and len(out) < 30:
        i += 1
        out.append(lines[i - 1])
        depth += lines[i - 1].count("(") - lines[i - 1].count(")")
    return "\n".join(out)


def classify(path, lineno, rule, stmt):
    if (path, lineno) in SITE:
        return SITE[(path, lineno)]
    fields = [e.strip() for e in re.findall(r"\{([^{}]*)\}", stmt) if e.strip()]
    if not fields:
        raise SystemExit("no classification for %s:%d (%s)" % (path, lineno, rule))
    kinds = []
    details = []
    for field in fields:
        key = (path, field)
        if key not in GROUP:
            raise SystemExit("no group for %s:%d field %r" % (path, lineno, field))
        kind, detail = GROUP[key]
        kinds.append(kind)
        details.append(detail)
    kind = kinds[0]
    if len(set(kinds)) != 1:
        kind = "mixed"
    return kind, " and ".join(dict.fromkeys(details))


def build(report_path, repo, commit, cache):
    report = json.load(open(report_path))
    out = []
    for finding in report["findings"]:
        path = finding["path"]
        lineno = finding["start_line"]
        stmt = statement(repo_lines(repo, commit, path, cache), lineno)
        kind, detail = classify(path, lineno, finding["rule_id"], stmt)
        if kind == "mixed":
            reason = ("The statement interpolates several values, each a "
                      "constant or a literal-bound parameter: %s. None of them "
                      "is request, argument or database data." % detail)
        else:
            reason = REASONS[kind].format(detail=detail)
        first = stmt.splitlines()[0].strip()
        if len(first) > 200:
            first = first[:197] + "..."
        span = len(stmt.splitlines())
        where = ("%s:%d" % (path, lineno)) if span == 1 \
            else ("%s:%d-%d" % (path, lineno, lineno + span - 1))
        out.append({
            "finding": finding["id"],
            "disposition": "not-a-bug",
            "date": DATE,
            "reason": reason,
            "note": "Observed at %s (%s); source: %s%s"
                    % (where, finding["rule_id"], first,
                       "" if span == 1 else " (+%d lines)" % (span - 1)),
        })
    ids = [f["id"] for f in report["findings"]]
    assert [e["finding"] for e in out] == ids, "triage is not in report order"
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default="/home/admini/projects/rbac_pg")
    ap.add_argument("--commit", default="d97860929b40a7a1f65e7b6a8cef66e72ef1cf4f")
    ap.add_argument("--bandit", required=True)
    ap.add_argument("--semgrep", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    cache = {}
    data = {
        "bandit": build(args.bandit, args.repo, args.commit, cache),
        "semgrep": build(args.semgrep, args.repo, args.commit, cache),
    }
    with open(args.out, "w", encoding="utf-8") as handle:
        yaml.safe_dump(data, handle, sort_keys=False, allow_unicode=True,
                       width=100)
    print("bandit %d, semgrep %d" % (len(data["bandit"]), len(data["semgrep"])),
          file=sys.stderr)


if __name__ == "__main__":
    main()
